#!/usr/bin/env bash
# ============================================================================
# Virtus Setup Script
# ============================================================================
# Local-first fork of Hermes Agent. This script:
#   1. Bootstraps ~/.virtus/ (config dir) if missing
#   2. Copies / links the fork repo into ~/.virtus/virtus-agent
#   3. Reuses the upstream installer for the heavy lifting (deps, venv)
#   4. Adds `virtus` (and `virtus-agent`, `virtus-acp`) into ~/.local/bin
#   5. Writes a default config.yaml with portal telemetry / auto-update
#      features turned off, sensitive_paths guard enabled
#
# Usage:
#   ./setup-virtus.sh                      # from the repo dir
#   ./setup-virtus.sh --skip-install       # config only, no deps
#
# Notes:
#   - All "use Nous free tier" / portal paths are stripped (run_sign_in
#     stubs, no anon_auth, no achievements plugin).
#   - Hermes aliases are KEPT alongside the `virtus` console scripts, so
#     any leftover cron / shell hooks pointing at `hermes` continue to
#     resolve to the same Python entry point.
#   - Model catalog (models.dev) defaults to "disk cache only" — the user
#     opts into a network refresh with `virtus config set models_dev
#     allow_network true`.
# ============================================================================

set -e

GREEN='\033[0;32m'
YELLOW='\033[0;33m'
CYAN='\033[0;36m'
RED='\033[0;31m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ ! -f "$SCRIPT_DIR/pyproject.toml" ] || ! grep -q 'name = "virtus-agent"' "$SCRIPT_DIR/pyproject.toml"; then
    echo -e "${RED}✗${NC} $(basename "$SCRIPT_DIR") does not look like a Virtus checkout."
    echo "  Expected pyproject.toml with name = \"virtus-agent\"."
    exit 1
fi

VIRTUS_HOME="${VIRTUS_HOME:-$HOME/.virtus}"

echo ""
echo -e "${CYAN}☤ Virtus Setup${NC}"
echo ""

mkdir -p "$VIRTUS_HOME"

# ---- 1. Reuse the existing venv (or run upstream installer) ---------------
SKIP_INSTALL=0
for arg in "$@"; do
    [ "$arg" = "--skip-install" ] && SKIP_INSTALL=1
done

if [ "$SKIP_INSTALL" -eq 0 ]; then
    if [ -x "$SCRIPT_DIR/venv/bin/python" ]; then
        echo -e "${GREEN}✓${NC} venv already present at $SCRIPT_DIR/venv"
    elif [ -x "$HOME/.hermes/hermes-agent/venv/bin/python" ]; then
        echo -e "${CYAN}→${NC} Reusing existing python venv from upstream install (saves reinstall time)"
        ln -s "$HOME/.hermes/hermes-agent/venv" "$SCRIPT_DIR/venv"
    else
        echo -e "${CYAN}→${NC} Running the upstream installer for dependencies…"
        bash "$SCRIPT_DIR/setup-hermes.sh"
    fi
fi

# ---- 2. Symlink the `virtus` launcher into ~/.local/bin/ ------------------
get_command_link_dir() {
    if [ -n "${PREFIX:-}" ] && [[ "${PREFIX:-}" == *"com.termux/files/usr"* ]]; then
        echo "$PREFIX/bin"
    else
        echo "$HOME/.local/bin"
    fi
}
LINK_DIR="$(get_command_link_dir)"
mkdir -p "$LINK_DIR"

install_launcher() {
    local src="$1"
    local name="$2"
    ln -sf "$src" "$LINK_DIR/$name"
    echo -e "${GREEN}✓${NC} $LINK_DIR/$name → $src"
}

install_launcher "$SCRIPT_DIR/virtus"          "virtus"
install_launcher "$SCRIPT_DIR/virtus"          "hermes"   # alias for upstream-compat
[ -f "$SCRIPT_DIR/run_agent.py" ] && ln -sf "$SCRIPT_DIR/venv/bin/virtus-agent" "$LINK_DIR/virtus-agent"
[ -f "$SCRIPT_DIR/acp_adapter/entry.py" ] && ln -sf "$SCRIPT_DIR/venv/bin/virtus-acp" "$LINK_DIR/virtus-acp"

# ---- 3. Write the default config.yaml ------------------------------------
CONFIG_PATH="$VIRTUS_HOME/config.yaml"
if [ -f "$CONFIG_PATH" ]; then
    echo -e "${CYAN}→${NC} $CONFIG_PATH already exists; not overwriting."
else
    cat > "$CONFIG_PATH" <<'YAML'
# Virtus config — generated by setup-virtus.sh
# Models / providers / tools / etc. follow the upstream schema. Sections
# starting with `sensitive_paths`, `updates`, `monitoring`, `account_usage`
# are Virtus-specific (off by default for everything that phones home).

model:
  default: MiniMax-M3
  provider: minimax
  base_url: https://api.minimax.io/anthropic

agent:
  max_turns: 90
  verbose: false
  reasoning_effort: medium

terminal:
  backend: local
  cwd: .
  timeout: 180

compression:
  enabled: false

# ─── Virtus-only switches ────────────────────────────────────────────────

# models.dev catalog: enabled but network-refresh is OFF by default.
# The file / disk cache is what gets read; opt in for one session with:
#   virtus config set models_dev.allow_network true
models_dev:
  allow_network: false
  url: ""

# Update-check banner / `virtus update` notification. Off by default;
# the only way to update the fork is `virtus sync upstream --apply`.
updates:
  notify: false
  auto_maintenance: false

# Account-usage fetch for OAuth providers (Anthropic, Codex, Minimax).
# Off by default; opt in with `virtus config set account_usage.fetch true`.
account_usage:
  fetch: false

# OTLP / observability export (the upstream `monitoring` block renamed,
# disabled by default, and stripped of the LAN-bound defaults).
monitoring:
  enabled: false

# Sensitive-path guard. Edit `guarded` to fit your machine; granted paths
# land in `allowed`. Session grants are in-memory only and reset at boot.
sensitive_paths:
  enabled: true
  guarded:
    - "~/.ssh/"
    - "~/.gnupg/"
    - "~/.aws/"
    - "~/.config/gh/"
    - "~/.kube/"
    - "~/.netrc"
    - "**/*.pem"
    - "**/*.key"
    - "**/id_rsa*"
    - "~/.bashrc"
    - "~/.zshrc"
    - "~/.profile"
    - "~/.bash_profile"
  allowed: []
YAML
    echo -e "${GREEN}✓${NC} Wrote $CONFIG_PATH"
fi

# ---- 4. Mirror existing .env (your API key) into ~/.virtus/.env -----------
ENV_PATH="$VIRTUS_HOME/.env"
if [ -f "$HOME/.hermes/.env" ] && [ ! -f "$ENV_PATH" ]; then
    echo -e "${CYAN}→${NC} Mirroring ~/.hermes/.env into $ENV_PATH"
    cp -p "$HOME/.hermes/.env" "$ENV_PATH"
    chmod 600 "$ENV_PATH"
fi

# ---- 5. Mark bundled skills as opt-out (mirrors your upstream choice) ----
touch "$VIRTUS_HOME/.no-bundled-skills"

# ---- 6. Done --------------------------------------------------------------
cat <<EOF

${GREEN}Virtus is installed.${NC}

Try it:
    $ virtus --version
    $ virtus                  # interactive REPL
    $ virtus setup            # first-run provider wizard (BYO key; all providers)
    $ virtus sync upstream    # preview upcoming upstream changes

Notes:
  - Hermes/Virtus port paths:    ~/.virtus/  (was  ~/.hermes/)
  - Bundled skills: shipped but not auto-loaded. Install on demand:
        virtus skills install <name>
  - Sensitive-path guard: enabled by default. ~/.ssh, ~/.gnupg, and the
    fork's own config files require explicit approval at read/write.
  - Update / merge model: NO auto-update. Manual `virtus sync upstream`.

EOF
